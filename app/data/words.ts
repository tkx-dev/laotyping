export function getRandomLaoWords(count: number): string[] {
  const result: string[] = [];
  const len = LAO_COMMON_WORDS.length;
  for (let i = 0; i < count; i++) {
    const randomIndex = Math.floor(Math.random() * len);
    result.push(LAO_COMMON_WORDS[randomIndex] || "ສະບາຍດີ");
  }
  return result;
}

